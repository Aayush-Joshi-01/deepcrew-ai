"""
Live integration tests — opt-in, real LLM calls.

Run with ``pytest --live`` and ``GEMINI_API_KEY`` set. By default every test here
is skipped, so the normal ``pytest`` run stays fully mocked and offline.

A content-hash ledger (``LEDGER.json`` / ``LEDGER.md``) records which features
have passed a live test. A feature whose ``watch`` source files are byte-identical
to the last recorded pass is skipped again — so a green feature is not re-billed
until its code changes. ``--relive`` forces every live test to run.

Each live test declares what it covers::

    pytestmark = pytest.mark.live(
        feature="episodic_memory",
        watch=["src/deepcrew/episodic_memory.py", "src/deepcrew/runner.py"],
    )
"""

from __future__ import annotations

import hashlib
import json
import os
import time
from pathlib import Path

import pytest

_DIR = Path(__file__).parent
_REPO = _DIR.parent.parent
LEDGER_JSON = _DIR / "LEDGER.json"
LEDGER_MD = _DIR / "LEDGER.md"

DEFAULT_MODEL = "gemini/gemini-3.5-flash-lite"

_passed_this_run: list[tuple[str, str, list[str]]] = []


# --- ledger helpers -----------------------------------------------------


def _load_ledger() -> dict:
    if LEDGER_JSON.exists():
        try:
            return json.loads(LEDGER_JSON.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            return {}
    return {}


def _watch_hash(watch: list[str]) -> str:
    h = hashlib.sha256()
    for rel in sorted(watch):
        path = _REPO / rel
        h.update(rel.encode("utf-8"))
        h.update(b"\0")
        h.update(path.read_bytes() if path.exists() else b"<missing>")
        h.update(b"\0")
    return h.hexdigest()


def _is_current(feature: str, watch: list[str]) -> tuple[bool, str]:
    entry = _load_ledger().get(feature)
    if not entry or entry.get("status") != "passed":
        return False, ""
    if entry.get("hash") != _watch_hash(watch):
        return False, ""
    return True, f"{entry.get('last_passed', '?')} ({entry.get('model', '?')})"


def _resolved_model() -> str:
    return os.environ.get("DEEPCREW_LIVE_MODEL", DEFAULT_MODEL)


def _regenerate_markdown(data: dict) -> None:
    lines = [
        "# Live-test ledger",
        "",
        "Auto-generated by `tests/live/conftest.py` on each `pytest --live` pass.",
        "A feature is skipped on the next run while its `watch` files are unchanged;",
        "edit any watched file (or pass `--relive`) to re-arm it.",
        "",
        "| Feature | Status | Last live pass | Model | Watches |",
        "| --- | --- | --- | --- | --- |",
    ]
    for feature in sorted(data):
        e = data[feature]
        watches = "<br>".join(f"`{w}`" for w in e.get("watch", []))
        passed = e.get("last_passed") or "-"
        model = e.get("model") or "-"
        lines.append(
            f"| `{feature}` | {e.get('status') or '?'} | {passed} | `{model}` | {watches} |"
        )
    lines.append("")
    LEDGER_MD.write_text("\n".join(lines), encoding="utf-8")


def _record_pass(feature: str, test: str, watch: list[str]) -> None:
    data = _load_ledger()
    data[feature] = {
        "test": test,
        "watch": sorted(watch),
        "status": "passed",
        "hash": _watch_hash(watch),
        "last_passed": time.strftime("%Y-%m-%d", time.gmtime()),
        "model": _resolved_model(),
    }
    LEDGER_JSON.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    _regenerate_markdown(data)


# --- pytest hooks -----------------------------------------------------


def pytest_addoption(parser: pytest.Parser) -> None:
    parser.addoption("--live", action="store_true", default=False, help="run live LLM tests")
    parser.addoption(
        "--relive",
        action="store_true",
        default=False,
        help="ignore the ledger; run every live test",
    )


def pytest_collection_modifyitems(config: pytest.Config, items: list[pytest.Item]) -> None:
    run_live = config.getoption("--live")
    relive = config.getoption("--relive")
    has_key = bool(os.environ.get("GEMINI_API_KEY"))

    for item in items:
        marker = item.get_closest_marker("live")
        if marker is None:
            continue
        if not (run_live or relive):
            item.add_marker(pytest.mark.skip(reason="live test (pass --live to run)"))
            continue
        if not has_key:
            item.add_marker(pytest.mark.skip(reason="GEMINI_API_KEY not set"))
            continue
        feature = marker.kwargs.get("feature")
        watch = marker.kwargs.get("watch", [])
        if feature and not relive:
            current, when = _is_current(feature, watch)
            if current:
                item.add_marker(
                    pytest.mark.skip(
                        reason=f"unchanged since live pass on {when}; --relive to force"
                    )
                )


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item: pytest.Item, call: pytest.CallInfo):
    outcome = yield
    report = outcome.get_result()
    if report.when != "call" or not report.passed:
        return
    marker = item.get_closest_marker("live")
    if marker is None or "feature" not in marker.kwargs:
        return
    _passed_this_run.append(
        (marker.kwargs["feature"], item.nodeid.split("::")[0], list(marker.kwargs.get("watch", [])))
    )


def pytest_sessionfinish(session: pytest.Session, exitstatus: int) -> None:
    seen: set[str] = set()
    for feature, test, watch in _passed_this_run:
        if feature in seen:
            continue
        seen.add(feature)
        _record_pass(feature, test, watch)


